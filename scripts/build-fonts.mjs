// Writes src/styles/fonts.css: @font-face rules for the three Source faces,
// self-hosted from the @fontsource-variable packages (bundled by Vite) under
// the family names the tokens use. Latin and Latin Extended subsets only.
// No Google Fonts: a font CDN sends every visitor's IP address to a third party.
// Run with `pnpm fonts` after updating the font packages.
import { readFileSync, writeFileSync } from "node:fs";

const faces = [
  { pkg: "source-sans-3", css: "wght.css", family: "Source Sans 3" },
  { pkg: "source-serif-4", css: "opsz.css", family: "Source Serif 4" },
  { pkg: "source-serif-4", css: "opsz-italic.css", family: "Source Serif 4" },
  { pkg: "source-code-pro", css: "wght.css", family: "Source Code Pro" },
];

let out = "/* Generated by scripts/build-fonts.mjs. Do not edit. */\n";
for (const { pkg, css, family } of faces) {
  const src = readFileSync(
    new URL(`../node_modules/@fontsource-variable/${pkg}/${css}`, import.meta.url),
    "utf8",
  );
  for (const block of src.split(/(?=\/\* )/)) {
    if (!/^\/\* [\w-]+-(latin|latin-ext)-/.test(block)) continue;
    out +=
      block
        .replace(/font-family: '[^']+'/, `font-family: "${family}"`)
        .replace(/url\(\.\/files\//g, `url(@fontsource-variable/${pkg}/files/`)
        .trim() + "\n";
  }
}
writeFileSync(new URL("../src/styles/fonts.css", import.meta.url), out);
console.log("Wrote src/styles/fonts.css");
